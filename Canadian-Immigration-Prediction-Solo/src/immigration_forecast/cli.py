"""Command line entry point.

    python -m immigration_forecast download
    python -m immigration_forecast run --models naive,seasonal_naive,ets,sarima,lightgbm,timesfm
    python -m immigration_forecast bq-forecast --project MY_PROJECT --dataset immigration
    python -m immigration_forecast summarize
"""

import argparse
import re
from pathlib import Path

import pandas as pd

from . import config
from .download import download_workbook
from .load import load_workbook
from .models import get_models
from .pipeline import months_until, run_series
from .plotting import plot_forecast
from .series import country_series, national_series, top_countries
from .validate import validate

CLASSICAL = "naive,seasonal_naive,ets,sarima"


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def _load_series(input_path: Path, top: int, processed_dir: Path | None = None) -> list[pd.Series]:
    data = load_workbook(input_path)
    report = validate(data)
    print(
        f"Loaded {report.n_countries} countries, {report.n_months} months "
        f"({report.first_month:%Y-%m} to {report.last_month:%Y-%m}); "
        f"{report.suppressed_share:.1%} of country-months suppressed; "
        f"max monthly gap vs published total = {report.max_total_gap:,.0f}"
    )
    for warning in report.warnings:
        print(f"WARNING: {warning}")

    if processed_dir is not None:
        processed_dir.mkdir(parents=True, exist_ok=True)
        data.countries.to_csv(processed_dir / "admissions_by_country_month.csv", index=False)

    series = [national_series(data)]
    for country in top_countries(data, top):
        try:
            series.append(country_series(data, country))
        except ValueError as err:
            print(f"Skipping: {err}")
    return series


def cmd_download(args) -> None:
    path = download_workbook(dest=Path(args.output))
    print(f"Saved {path} ({path.stat().st_size:,} bytes)")


def cmd_run(args) -> None:
    models = get_models([m.strip() for m in args.models.split(",") if m.strip()])
    series = _load_series(Path(args.input), args.top, Path(args.processed_dir))

    reports = Path(args.reports_dir)
    all_metrics, all_forecasts = [], []
    for y in series:
        result = run_series(y, args.forecast_end, horizon=args.horizon, n_folds=args.folds, step=args.step, models=models)
        print(f"\n{result.series}: best model = {result.best_model}")
        print(result.metrics.round(1).to_string())

        all_metrics.append(result.metrics.reset_index().assign(series=result.series))
        all_forecasts.append(result.forecast.reset_index().assign(series=result.series, model=result.best_model))
        plot_forecast(
            y,
            result.forecast,
            f"{result.series}: monthly PR admissions, forecast with {result.best_model}",
            reports / "figures" / f"forecast_{_slug(result.series)}.png",
        )

    reports.mkdir(parents=True, exist_ok=True)
    metrics = pd.concat(all_metrics)[["series", "model", "mae", "rmse", "mape_pct", "interval_coverage_pct", "n_forecasts"]]
    metrics.round(2).to_csv(reports / "backtest_metrics.csv", index=False)
    forecasts = pd.concat(all_forecasts)[["series", "model", "date", "mean", "lower", "upper"]]
    forecasts.round(0).to_csv(reports / "forecasts.csv", index=False)
    print(f"\nWrote {reports / 'backtest_metrics.csv'}, {reports / 'forecasts.csv'} and figures.")


def cmd_bq_forecast(args) -> None:
    from google.cloud import bigquery

    from .gcp.bigquery import run_bigquery_forecasts, to_bigquery_frame

    series = _load_series(Path(args.input), args.top)
    horizon = months_until(series[0], args.forecast_end)
    client = bigquery.Client(project=args.project, location=args.location)
    result = run_bigquery_forecasts(
        client, args.project, args.dataset, to_bigquery_frame(series), horizon, timesfm_model=args.timesfm_model
    )
    out = Path(args.reports_dir) / "bigquery_forecasts.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    result.round(0).to_csv(out, index=False)
    print(f"Wrote {out} ({len(result)} rows from {result['model'].nunique()} BigQuery methods)")


def cmd_summarize(args) -> None:
    from .gcp.gemini import build_prompt, summarize_with_gemini

    reports = Path(args.reports_dir)
    metrics = pd.read_csv(reports / "backtest_metrics.csv")
    forecasts = pd.read_csv(reports / "forecasts.csv", parse_dates=["date"])
    last_month = (forecasts["date"].min() - pd.offsets.MonthBegin(1)).strftime("%B %Y")
    prompt = build_prompt(metrics, forecasts, last_month)
    if args.print_prompt:
        print(prompt)
        return
    text = summarize_with_gemini(prompt, model=args.gemini_model)
    out = reports / "summary_gemini.md"
    out.write_text(f"# Forecast briefing (generated by Gemini)\n\n{text.strip()}\n", encoding="utf-8")
    print(f"Wrote {out}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="immigration_forecast", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("download", help="download the IRCC workbook")
    p.add_argument("--output", default=str(config.RAW_FILE))
    p.set_defaults(func=cmd_download)

    p = sub.add_parser("run", help="validate, backtest, forecast and write reports")
    p.add_argument("--input", default=str(config.RAW_FILE))
    p.add_argument("--processed-dir", default=str(config.PROCESSED_DIR))
    p.add_argument("--reports-dir", default=str(config.REPORTS_DIR))
    p.add_argument("--models", default=CLASSICAL, help=f"comma-separated; add lightgbm,timesfm (default: {CLASSICAL})")
    p.add_argument("--top", type=int, default=5, help="also model the N largest source countries")
    p.add_argument("--forecast-end", default="2027-12", help="last month to forecast (YYYY-MM)")
    p.add_argument("--horizon", type=int, default=12, help="months ahead scored in each backtest fold")
    p.add_argument("--folds", type=int, default=8)
    p.add_argument("--step", type=int, default=3, help="months between backtest origins")
    p.set_defaults(func=cmd_run)

    p = sub.add_parser("bq-forecast", help="forecast in BigQuery with ARIMA_PLUS and AI.FORECAST (TimesFM)")
    p.add_argument("--project", required=True, help="GCP project id")
    p.add_argument("--dataset", default="immigration_forecast")
    p.add_argument("--location", default="US")
    p.add_argument("--input", default=str(config.RAW_FILE))
    p.add_argument("--reports-dir", default=str(config.REPORTS_DIR))
    p.add_argument("--top", type=int, default=5)
    p.add_argument("--forecast-end", default="2027-12")
    p.add_argument("--timesfm-model", default=None, help="AI.FORECAST model name; omit for BigQuery's default")
    p.set_defaults(func=cmd_bq_forecast)

    p = sub.add_parser("summarize", help="plain-language briefing of reports/ with Gemini")
    p.add_argument("--reports-dir", default=str(config.REPORTS_DIR))
    p.add_argument("--gemini-model", default=None, help="defaults to $GEMINI_MODEL or gemini-2.5-flash")
    p.add_argument("--print-prompt", action="store_true", help="print the prompt only, no API call")
    p.set_defaults(func=cmd_summarize)
    return parser


def main(argv=None) -> None:
    args = build_parser().parse_args(argv)
    args.func(args)
